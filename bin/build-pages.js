// Builds the static showcase site that GitHub Pages serves from the top of the repository.
// It has the full home page and the sample report. Live audits need the Node server, so the
// showcase turns the audit form into an emailed request instead.
//
// Run it after changing anything in public/:  npm run build:pages
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(ROOT, 'public');
const SITE = path.join(ROOT, 'site');

// The sample report is generated in a throwaway folder so it never touches real reports.
const scratch = mkdtempSync(path.join(os.tmpdir(), 'viralyst-pages-'));
process.env.DATA_DIR = scratch;
process.env.ENV_FILE = path.join(scratch, 'none.env');
const { runDemoAudit, loadReport } = await import('../src/audit.js');

try {
  const demo = await runDemoAudit({ timezone: 'Asia/Kolkata', brief: { goal: 'Sales', idealCustomer: '', markets: '' } });
  const report = loadReport(demo.id);

  rmSync(SITE, { recursive: true, force: true });
  mkdirSync(SITE, { recursive: true });
  for (const file of ['app.js', 'charts.js', 'style.css', 'favicon.svg']) copyFileSync(path.join(PUBLIC, file), path.join(SITE, file));
  writeFileSync(path.join(SITE, 'sample-report.json'), JSON.stringify(report));

  // GitHub Pages serves the site from a sub-path, so every asset link becomes relative.
  let html = readFileSync(path.join(PUBLIC, 'index.html'), 'utf8')
    .replace('href="/style.css"', 'href="site/style.css"')
    .replace('src="/app.js"', 'src="site/app.js"')
    .replaceAll('href="/favicon.svg"', 'href="site/favicon.svg"')
    .replace('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="viralyst-static" content="true">');
  html = `<!-- Generated by npm run build:pages from public/index.html. Edit that file, not this one. -->\n${html}`;
  writeFileSync(path.join(ROOT, 'index.html'), html);
  // Tells GitHub Pages to serve the files as they are, without its Jekyll processing.
  writeFileSync(path.join(ROOT, '.nojekyll'), '');

  console.log(`Built the showcase: index.html and site/ (sample report ${report.id}).`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
